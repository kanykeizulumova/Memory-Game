function startNewGame(gameBoard) {
    state.cards = createDeck(library[state.theme], 8);
    state.flippedCards = [];
    state.isLocked = false;
    state.moves = 0;
    state.status = 'playing';

    renderBoard(gameBoard);
}


const createDeck = (items, pairCount = 8) => {
    const selected = items.slice(0, pairCount);
    const deck = [...selected, ...selected].map((item, index) => ({
        uniqueId: index,
        id: item.id,
        image: item.image,
        isFlipped: false,
        isMatched: false
    }));
    return shuffle(deck);
};

function shuffle(array) {
    const arr = [...array];
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}

function handleCardClick(cardId) {
    const card = state.cards.find(c => c.uniqueId === cardId);

    if (state.status === 'won' || state.isLocked || !card || card.isFlipped || card.isMatched) {
        return;
    }
    card.isFlipped = true;

    const cardElement = document.querySelector(`[data-id="${cardId}"]`);

    if (cardElement) {
        cardElement.classList.add('is-flipped');
        cardElement.dataset.state = 'flipped';
    }

    state.flippedCards.push(card);
    if (state.flippedCards.length === 1) {
        return;
    }

    if (state.flippedCards.length === 2) {
        checkPairMatch();
    }
}

function checkPairMatch() {
    state.moves++;
    const movesOutput = document.getElementById('moves-count');
    const pairsOutput = document.getElementById('pairs-count');
    if (movesOutput) movesOutput.textContent = String(state.moves);

    const [card1, card2] = state.flippedCards;

    const el1 = document.querySelector(`[data-id="${card1.uniqueId}"]`);
    const el2 = document.querySelector(`[data-id="${card2.uniqueId}"]`);

    if (card1.id === card2.id) {
        card1.isMatched = true;
        card2.isMatched = true;
        pairsOutput.textContent = `${(state.cards.filter(card => card.isMatched).length) / 2} из ${state.cards.length / 2}`;

        if (el1) {
            el1.classList.add('is-matched');
            el1.dataset.state = 'matched';
        }
        if (el2) {
            el2.classList.add('is-matched');
            el2.dataset.state = 'matched';
        }

        state.flippedCards = [];

        checkGameWin();
    } else {

        state.isLocked = true;

        setTimeout(() => {
            card1.isFlipped = false;
            card2.isFlipped = false;

            if (el1) {
                el1.classList.remove('is-flipped');
                el1.dataset.state = 'closed';
            }
            if (el2) {
                el2.classList.remove('is-flipped');
                el2.dataset.state = 'closed';
            }

            state.flippedCards = [];
            state.isLocked = false;
        }, 1000);
    }
}

function checkGameWin() {
    const matchedCount = state.cards.filter(card => card.isMatched).length;
    const totalPairs = state.cards.length;
    const dialog = document.getElementById('victory-modal');

    if (matchedCount === totalPairs) {
        state.status = 'won';
        console.log('You won the game!');
        setTimeout(() => {
            dialog.showModal();
            const finalMovesCount = document.getElementById('final-moves-count');
            finalMovesCount.textContent = String(state.moves);
        }, 1000);
    }
};

